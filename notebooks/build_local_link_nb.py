        "%matplotlib inline\n"
        "import matplotlib.pyplot as plt\n"
        "FIG = WORK / 'outputs' / 'figures'; FIG.mkdir(parents=True, exist_ok=True)\n"
        "def _save(fig, name):\n"
        "    fig.tight_layout(); fig.savefig(FIG / name, dpi=120); plt.show()\n\n"
